"""Scenario hygiene: the curated set + the quarantine mechanism.

The auto-generated cat-* corpus was retired (deliberate curation —
keep only hand-authored, rigor-checked decision problems). What
remains under test: every active pack is hand-authored and meaningful,
and the quarantine mechanism (files on disk, excluded from the default
sweep, still runnable by explicit --packs) still holds via the harvest
packs blocked on the engine S0/S1 prerequisite.
"""

from __future__ import annotations

import glob
import os
from pathlib import Path

from openra_bench import run_eval
from openra_bench.scenarios import load_pack

PACKS = Path(__file__).parent.parent / "openra_bench" / "scenarios" / "packs"


def _all_metas():
    out = []
    for f in glob.glob(str(PACKS / "*.yaml")):
        if os.path.basename(f).startswith(("_", "TEMPLATE")):
            continue
        out.append((os.path.basename(f), load_pack(f).meta))
    return out


def test_no_autogenerated_cat_packs_remain():
    assert not list(PACKS.glob("cat-*.yaml")), "cat-* corpus must be gone"


def test_curated_set_is_small_handauthored_and_meaningful():
    metas = _all_metas()
    active = [(n, m) for n, m in metas if m.status == "active"]
    # Deliberately curated: a couple dozen, not hundreds.
    assert 15 <= len(active) <= 40, f"active set size {len(active)}"
    for name, m in active:
        assert not name.startswith("cat-")
        assert len(m.real_world_meaning) >= 20  # genuine transfer story
        assert len(m.robotics_analogue) >= 10
    for name, m in metas:
        assert m.status in ("active", "quarantine")
        if m.status == "quarantine":
            assert m.quarantine_reason, f"{name} quarantined w/o reason"


def test_harvest_quarantined_with_engine_reason():
    # economy-harvest-timebox was un-quarantined after task #14 wired
    # real harvest income / silo storage end-to-end; the investment
    # pack still rides the S0/S1 quarantine until storage-capacity work
    # lands.
    m = load_pack(PACKS / "economy-harvest-investment.yaml").meta
    assert m.status == "quarantine"
    assert "S0/S1" in m.quarantine_reason


def test_default_evaluate_excludes_quarantine_keeps_active(monkeypatch):
    # Real resolver + a tiny fake compile (no engine): quarantined ids
    # land in `skipped` and are never compiled; active ones are.
    captured: dict = {}

    def fake_compile(pack, level):
        captured.setdefault("compiled", []).append(pack.meta.id)

        class C:
            map_supported = False  # short-circuit into skipped

        c = C()
        c.meta = pack.meta
        return c

    monkeypatch.setattr(run_eval, "compile_level", fake_compile)
    packs = run_eval._resolve_packs(None)
    out = run_eval.evaluate(packs=packs, levels=["easy"], seeds=[1])
    sk = " ".join(out["skipped"])
    assert "quarantine:" in sk
    # economy-harvest-investment is the remaining harvest-family
    # quarantined pack (timebox was un-quarantined post-#14).
    assert any("economy-harvest-investment" in s for s in out["skipped"])
    assert "economy-harvest-investment" not in captured.get("compiled", [])
    # a curated active pack reached the (faked) compile step
    assert "rush-hour" in captured.get("compiled", [])


def test_quarantined_pack_still_loads_when_named_explicitly():
    p = load_pack(PACKS / "economy-harvest-investment.yaml")
    assert (
        p.meta.status == "quarantine"
        and p.meta.id == "economy-harvest-investment"
    )
